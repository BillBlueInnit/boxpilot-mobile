"""Generates lib/i18n/strings_desktop.g.dart from the desktop app's translations.

    python scripts/gen_i18n.py [path/to/boxpilot/crates/app/src/i18n.rs]

Both apps then use the same wording and the same four languages. Strings that
only the phone app needs live in lib/i18n/strings_mobile.dart.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(ROOT, "..", "..", "rust", "boxpilot", "crates", "app", "src", "i18n.rs")


def rust_strings(text, pos):
    """Yields (value, end) for each "…" literal starting at or after pos."""
    i = pos
    while True:
        i = text.find('"', i)
        if i < 0:
            return
        j, out = i + 1, []
        while text[j] != '"':
            if text[j] == "\\":
                nxt = text[j + 1]
                out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'", "0": "\0"}.get(nxt, nxt))
                j += 2
            else:
                out.append(text[j])
                j += 1
        yield "".join(out), j + 1
        i = j + 1


def parse(text):
    start = text.index("TABLE")
    entries = []
    for m in re.finditer(r'\(\s*"([a-z0-9_.]+)"\s*,\s*\[', text[start:]):
        key = m.group(1)
        pos = start + m.end()
        values = []
        for value, end in rust_strings(text, pos):
            values.append(value)
            pos = end
            if len(values) == 4:
                break
        entries.append((key, values))
    return entries


def dart(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    with open(src, encoding="utf-8") as f:
        entries = parse(f.read())
    lines = [
        "// GENERATED by scripts/gen_i18n.py from the desktop app's i18n.rs. Do not edit.",
        "// Columns: English, 简体中文, 繁體中文, Русский (an empty entry falls back to English).",
        "",
        "const Map<String, List<String>> desktopStrings = {",
    ]
    for key, values in entries:
        lines.append(f"  {dart(key)}: [{', '.join(dart(v) for v in values)}],")
    lines.append("};")
    out = os.path.join(ROOT, "lib", "i18n", "strings_desktop.g.dart")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(entries)} keys -> {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main()
